"""Build the standalone phone PWA from shared UI and the clean question template only."""
from pathlib import Path
import sqlite3,json,hashlib,struct,zlib
import transfer

ROOT=Path(__file__).resolve().parent
def icon(size):
    glyphs=['111 111 111','100 101 010','111 111 010','001 101 010','111 101 010']
    scale=size//19;x0=(size-11*scale)//2;y0=(size-5*scale)//2
    rows=[]
    for y in range(size):
        row=bytearray([0])
        for x in range(size):
            gx=(x-x0)//scale;gy=(y-y0)//scale
            white=0<=gy<5 and 0<=gx<11 and glyphs[gy][gx]=='1'
            row.extend((255,255,255) if white else (36,78,216))
        rows.append(row)
    def chunk(tag,data):return struct.pack('!I',len(data))+tag+data+struct.pack('!I',zlib.crc32(tag+data)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!2I5B',size,size,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b'')

def build():
    out=ROOT/'docs';out.mkdir(exist_ok=True)
    source=sqlite3.connect('file:'+str(ROOT/'sat-clean.db')+'?mode=ro',uri=True);db=sqlite3.connect(':memory:');db.row_factory=sqlite3.Row
    source.backup(db);source.close()
    for table in ['attempts','notes','review_state','personal_difficulty','question_tags','tags']:
        if db.execute('SELECT 1 FROM '+table+' LIMIT 1').fetchone():raise ValueError('Clean template has personal data; refusing to publish it')
    seed=transfer.export_bank(db);seed['bank']={'id':'sat-english-original-v1','name':'SAT English · fresh bank'}
    if any(seed[k] for k in ['attempts','notes','ratings','reviews','tags']):raise ValueError('Clean template contains transfer history')
    db.close()
    (out/'seed.json').write_text(json.dumps(seed,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    scripts=''.join(f'<script src="./{name}" defer></script>' for name in ['vendor/supabase.js','cloud-config.js','sync-engine.js','cloud.js','offline.js'])
    html=(ROOT/'web/index.html').read_text(encoding='utf-8').replace('/web/','./').replace('<!-- OFFLINE_ADAPTER -->',scripts).replace('</head>','<link rel="manifest" href="./manifest.webmanifest"><link rel="apple-touch-icon" href="./icon-192.png"><meta name="apple-mobile-web-app-capable" content="yes"></head>')
    (out/'index.html').write_text(html,encoding='utf-8')
    shared=['app.js','style.css','bank-core.js','offline.js','sync-engine.js','cloud.js','cloud-config.js','vendor/supabase.js','vendor/SUPABASE-LICENSE']
    for name in shared:
        (out/name).parent.mkdir(exist_ok=True);(out/name).write_bytes((ROOT/'web'/name).read_bytes())
    for size in [192,512]:(out/f'icon-{size}.png').write_bytes(icon(size))
    (out/'manifest.webmanifest').write_text(json.dumps({'id':'./','name':'SAT English Practice','short_name':'SAT English','description':'Offline SAT practice with your own notes and progress','start_url':'./','scope':'./','display':'standalone','background_color':'#ffffff','theme_color':'#244ed8','icons':[{'src':f'./icon-{size}.png','sizes':f'{size}x{size}','type':'image/png','purpose':'any maskable'} for size in [192,512]]}),encoding='utf-8')
    names=['index.html',*shared,'seed.json','manifest.webmanifest','icon-192.png','icon-512.png']
    version=hashlib.sha256(b''.join((out/n).read_bytes() for n in names)).hexdigest()[:16]
    sw="""// Generated by build_phone.py. Practice data lives in IndexedDB, never in this cache.
const PREFIX='sat-pwa:'+self.registration.scope+':',CACHE=PREFIX+'VERSION';
const FILES=FILES_JSON;
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const name of await caches.keys())if(name.startsWith(PREFIX)&&name!==CACHE)await caches.delete(name);await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data==='activate-update')self.skipWaiting();});
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET'||!event.request.url.startsWith(self.registration.scope))return;
 event.respondWith((async()=>{const cache=await caches.open(CACHE);if(event.request.mode==='navigate')return (await cache.match('./index.html'))||fetch(event.request);return (await cache.match(event.request,{ignoreSearch:true}))||fetch(event.request);})());
});
""".replace('VERSION',version).replace('FILES_JSON',json.dumps(['./'+n for n in names]))
    (out/'sw.js').write_text(sw,encoding='utf-8');(out/'.nojekyll').touch()
    print(f'Built phone app: {len(seed["questions"])} clean questions, cache {version}')
if __name__=='__main__':build()

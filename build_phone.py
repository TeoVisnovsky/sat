"""Build the standalone phone PWA from shared UI and the clean question template only."""
from pathlib import Path
import sqlite3,json,hashlib,struct,zlib,shutil
import transfer

ROOT=Path(__file__).resolve().parent
def icon(size):
    glyphs=['111 111 111','100 101 010','111 111 010','001 101 010','111 101 010']
    scale=size//19;x0=(size-11*scale)//2;y0=(size-5*scale)//2
    rows=[]
    for y in range(size):
        row=bytearray([0])
        for x in range(size):
            gx=(x-x0)//scale;gy=(y-y0)//scale
            white=0<=gy<5 and 0<=gx<11 and glyphs[gy][gx]=='1'
            row.extend((255,255,255) if white else (36,78,216))
        rows.append(row)
    def chunk(tag,data):return struct.pack('!I',len(data))+tag+data+struct.pack('!I',zlib.crc32(tag+data)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!2I5B',size,size,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b'')

def clean_seed(filename,bank_id,name):
    source=sqlite3.connect('file:'+str(ROOT/filename)+'?mode=ro',uri=True);db=sqlite3.connect(':memory:');db.row_factory=sqlite3.Row
    source.backup(db);source.close()
    transfer.migrate(db)
    for table in ['attempts','notes','review_state','personal_difficulty','question_tags','tags','full_test_sessions']:
        if db.execute('SELECT 1 FROM '+table+' LIMIT 1').fetchone():raise ValueError(filename+' has personal data; refusing to publish it')
    seed=transfer.export_bank(db);seed['bank']={'id':bank_id,'name':name};db.close()
    if any(seed[k] for k in ['attempts','notes','ratings','reviews','tags','test_sessions']):raise ValueError(filename+' contains transfer history')
    return seed

def build():
    out=ROOT/'docs';out.mkdir(exist_ok=True)
    seed=clean_seed('sat-clean.db','sat-english-original-v1','SAT English · fresh bank')
    math_seed=clean_seed('sat-math-clean.db','sat-math-original-v1','SAT Math · fresh bank')
    slovak_seed=clean_seed('maturita-slovak-clean.db','maturita-slovak','Maturita · Slovenský jazyk a literatúra')
    maturita_math_seed=clean_seed('maturita-math-clean.db','maturita-math','Maturita · Matematika')
    (out/'seed.json').write_text(json.dumps(seed,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    (out/'math-seed.json').write_text(json.dumps(math_seed,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    (out/'maturita-slovak-seed.json').write_text(json.dumps(slovak_seed,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    (out/'maturita-math-seed.json').write_text(json.dumps(maturita_math_seed,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    shutil.copytree(ROOT/'assets'/'maturita',out/'assets'/'maturita',dirs_exist_ok=True)
    scripts=''.join(f'<script src="./{name}" defer></script>' for name in ['vendor/supabase.js','cloud-config.js','sync-engine.js','cloud.js','offline.js'])
    html=(ROOT/'web/index.html').read_text(encoding='utf-8').replace('/web/','./').replace('<!-- OFFLINE_ADAPTER -->',scripts).replace('</head>','<link rel="manifest" href="./manifest.webmanifest"><link rel="apple-touch-icon" href="./icon-192.png"><meta name="apple-mobile-web-app-capable" content="yes"></head>')
    (out/'index.html').write_text(html,encoding='utf-8')
    shared=['app.js','style.css','bank-core.js','offline.js','sync-engine.js','cloud.js','cloud-config.js','vendor/supabase.js','vendor/SUPABASE-LICENSE']
    for name in shared:
        (out/name).parent.mkdir(exist_ok=True);(out/name).write_bytes((ROOT/'web'/name).read_bytes())
    for size in [192,512]:(out/f'icon-{size}.png').write_bytes(icon(size))
    (out/'manifest.webmanifest').write_text(json.dumps({'id':'./','name':'SAT and Maturita Practice','short_name':'Study Practice','description':'Offline SAT and Slovak Maturita practice with notes, progress and private sync','start_url':'./','scope':'./','display':'standalone','background_color':'#ffffff','theme_color':'#244ed8','icons':[{'src':f'./icon-{size}.png','sizes':f'{size}x{size}','type':'image/png','purpose':'any maskable'} for size in [192,512]]}),encoding='utf-8')
    names=['index.html',*shared,'seed.json','math-seed.json','maturita-slovak-seed.json','maturita-math-seed.json','manifest.webmanifest','icon-192.png','icon-512.png']
    asset_names=[p.relative_to(out).as_posix() for p in sorted((out/'assets'/'maturita').rglob('*.webp'))]
    version=hashlib.sha256(b''.join((out/n).read_bytes() for n in names)).hexdigest()[:16]
    sw="""// Generated by build_phone.py. Practice data lives in IndexedDB, never in this cache.
const PREFIX='sat-pwa:'+self.registration.scope+':',CACHE=PREFIX+'VERSION';
const CORE=CORE_JSON,BANK_FILES=BANK_FILES_JSON;
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const cache=await caches.open(CACHE);
 for(const file of CORE)await cache.add(new Request(file,{cache:'reload'}));
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const name of await caches.keys())if(name.startsWith(PREFIX)&&name!==CACHE)await caches.delete(name);await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data==='activate-update'){self.skipWaiting();return;}if(event.data?.type==='cache-bank')event.waitUntil((async()=>{const files=BANK_FILES[event.data.bank]||[],cache=await caches.open(CACHE);let loaded=0,failed=0;for(const file of files){if(!await cache.match(file))try{await cache.add(file);}catch(e){failed++;}loaded++;event.source?.postMessage({type:'cache-bank-progress',loaded,total:files.length,failed,done:loaded===files.length});}if(!files.length)event.source?.postMessage({type:'cache-bank-progress',loaded:0,total:0,failed:1,done:true});})());});
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET'||!event.request.url.startsWith(self.registration.scope))return;
 event.respondWith((async()=>{const cache=await caches.open(CACHE);if(event.request.mode==='navigate')return (await cache.match('./index.html'))||fetch(event.request);const saved=await cache.match(event.request,{ignoreSearch:true});if(saved)return saved;const response=await fetch(event.request);if(response.ok)cache.put(event.request,response.clone());return response;})());
});
""".replace('VERSION',version).replace('CORE_JSON',json.dumps(['./'+n for n in ['index.html',*shared,'manifest.webmanifest','icon-192.png','icon-512.png']])).replace('BANK_FILES_JSON',json.dumps({
        'main':['./seed.json'],
        'math':['./math-seed.json'],
        'maturita-slovak':['./maturita-slovak-seed.json',*['./'+n for n in asset_names if n.startswith('assets/maturita/slovak/')]],
        'maturita-math':['./maturita-math-seed.json',*['./'+n for n in asset_names if n.startswith('assets/maturita/math/')]],
    }))
    (out/'sw.js').write_text(sw,encoding='utf-8');(out/'.nojekyll').touch()
    print(f'Built web app: {len(seed["questions"])} SAT English + {len(math_seed["questions"])} SAT Math + {len(slovak_seed["questions"])} SJL + {len(maturita_math_seed["questions"])} Maturita Math, cache {version}')
if __name__=='__main__':build()
